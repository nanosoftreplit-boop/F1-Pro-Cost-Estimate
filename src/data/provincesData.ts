/**
 * Tìm kiếm thông tin tỉnh thành theo Tên hoặc ID
 */
export function findProvince(nameOrId: string): ProvinceData | undefined {
  if (!nameOrId) return undefined;
  const q = nameOrId.trim().toLowerCase();
  return PROVINCES_DATA.find(p => p.name.toLowerCase() === q || p.id.toLowerCase() === q);
}

/**
 * Lấy danh sách tên 63 tỉnh thành phố
 */
export const ALL_PROVINCE_NAMES: string[] = PROVINCES_DATA.map(p => p.name);
